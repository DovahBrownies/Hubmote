#!/usr/bin/env python3
"""
Generates components/hub/hub_tz.c: every time zone in the IANA tz database's
zone.tab (one or more per country, named by a city), each with its POSIX TZ
rule, which carries its daylight-saving changes. The remote's C library
applies the rule (setenv("TZ", ...)), so the table needs no updates for
daylight saving; it does when a country changes its rules.

The tz database is public domain. It comes from the `tzdata` package, at
the version CI checks hub_tz.c with (.github/workflows/build.yml); to move
to a newer tz release, raise it in both places:

    python -m pip install tzdata==2026.5
    python tools/time/gen_zones.py

The rule is the last line of each zone's TZif file (version 2 and later).
"""
import importlib.resources
import re
import sys
from pathlib import Path

try:
    import tzdata
except ImportError:
    sys.exit("needs the tzdata package: python -m pip install tzdata")

OUT = Path(__file__).resolve().parents[2] / "components" / "hub" / "hub_tz.c"
ROOT = importlib.resources.files("tzdata") / "zoneinfo"
# What the remote's C library (newlib) accepts: std offset [dst [offset] [,rules]].
POSIX = re.compile(r"^(<[^>]+>|[A-Za-z]{3,})[-+0-9:]+((<[^>]+>|[A-Za-z]{3,})([-+0-9:]+)?(,[^,]+,[^,]+)?)?$")


def rule(name):
    data = (ROOT.joinpath(*name.split("/"))).read_bytes()
    if not data.startswith(b"TZif") or data[4:5] not in (b"2", b"3", b"4"):
        sys.exit(f"{name}: not a TZif v2+ file")
    footer = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode("ascii")
    if not POSIX.match(footer):
        sys.exit(f"{name}: unexpected rule {footer!r}")
    return footer


def main():
    names = set()
    for line in (ROOT / "zone.tab").read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            names.add(line.split("\t")[2])
    names = sorted(names) + ["UTC"]
    rows = [f'    {{"{n}", "{rule(n)}"}},' for n in names]
    OUT.write_text(
        "/*\n"
        f" * Time zones: the IANA tz database {tzdata.IANA_VERSION} (public domain), every\n"
        " * zone in zone.tab and UTC, with its POSIX TZ rule. Generated by\n"
        " * tools/time/gen_zones.py: don't edit by hand, run it again.\n"
        " */\n"
        '#include "hub_tz.h"\n'
        "\n"
        "const hub_tz_t hub_tz[] = {\n" + "\n".join(rows) + "\n};\n"
        "\n"
        "const size_t hub_tz_count = sizeof(hub_tz) / sizeof(hub_tz[0]);\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{OUT.name}: {len(names)} zones from tz {tzdata.IANA_VERSION}")


if __name__ == "__main__":
    main()
