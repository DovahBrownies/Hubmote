#!/usr/bin/env python3
"""
Writes sim/lv_kconfig.h, LVGL's configuration for the PC simulator, from a
firmware build's sdkconfig.h: every CONFIG_LV_* the firmware uses, except
that LVGL allocates with the PC's malloc instead of the firmware's PSRAM
allocator (components/ui/ui_mem.c). Run it after changing LVGL options in
sdkconfig.defaults, then build the firmware once first:

    python sim/gen_lv_kconfig.py [build/config/sdkconfig.h]
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "build" / "config" / "sdkconfig.h"

# The firmware's own allocator lives in ui_mem.c; the simulator uses malloc.
OVERRIDES = {
    "CONFIG_LV_USE_CUSTOM_MALLOC": None,
    "CONFIG_LV_USE_STDLIB_MALLOC": "1",  # LV_STDLIB_CLIB
    "CONFIG_LV_USE_CLIB_MALLOC": "1",
}

lines = []
for line in SRC.read_text(encoding="utf-8").splitlines():
    m = re.match(r"#define (CONFIG_LV_\w+)(?: (.*))?$", line)
    if not m:
        continue
    name, value = m.group(1), m.group(2) or ""
    if name in OVERRIDES:
        continue
    lines.append(f"#define {name} {value}".rstrip())
for name, value in OVERRIDES.items():
    if value is not None:
        lines.append(f"#define {name} {value}")

out = HERE / "lv_kconfig.h"
out.write_text(
    "/* LVGL's configuration for the simulator: the firmware's CONFIG_LV_*\n"
    " * (from sdkconfig.h), with malloc for the allocator. Generated by\n"
    " * sim/gen_lv_kconfig.py; don't edit. */\n"
    "#pragma once\n" + "\n".join(lines) + "\n",
    encoding="utf-8", newline="\n")
print(f"{out}: {len(lines)} options")
